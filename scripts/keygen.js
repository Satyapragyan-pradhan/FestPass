/**
 * FestPass Keygen Script
 * Generates an Ed25519 cryptographic keypair for ticket signing and offline verification.
 * Saves keys to gitignored keys/ folder and prints instructions.
 */

const fs = require('fs');
const path = require('path');
const { generateEd25519KeyPair } = require('../packages/shared/src/tokens');

function runKeygen() {
  const keysDir = path.resolve(__dirname, '..', 'keys');
  if (!fs.existsSync(keysDir)) {
    fs.mkdirSync(keysDir, { recursive: true });
  }

  const { publicKey, privateKey } = generateEd25519KeyPair();

  const privateKeyPath = path.join(keysDir, 'ed25519-private.pem');
  const publicKeyPath = path.join(keysDir, 'ed25519-public.pem');

  fs.writeFileSync(privateKeyPath, privateKey, 'utf8');
  fs.writeFileSync(publicKeyPath, publicKey, 'utf8');

  console.log('====================================================');
  console.log('FestPass Ed25519 Keypair Generated Successfully!');
  console.log('====================================================');
  console.log(`Private Key: ${privateKeyPath}`);
  console.log(`Public Key:  ${publicKeyPath}`);
  console.log('\nSecurity Rule:');
  console.log('- Booth nodes hold the PRIVATE key (to sign and issue tickets)');
  console.log('- ALL nodes (booth + gate) hold the PUBLIC key (gates verify offline)');
  console.log('\nKeys have been saved to the keys/ folder.');
  console.log(
    'You may also copy the contents into .env as ED25519_PRIVATE_KEY and ED25519_PUBLIC_KEY.'
  );
  console.log('====================================================\n');

  // If .env doesn't exist, create it from .env.example or template
  const envPath = path.resolve(__dirname, '..', '.env');
  if (!fs.existsSync(envPath)) {
    const singleLinePrivate = privateKey.replace(/\r?\n/g, '\\n');
    const singleLinePublic = publicKey.replace(/\r?\n/g, '\\n');

    const envContent = `# FestPass Environment Configuration (Generated by npm run keygen)
PORT=4001
NODE_ID=B1
NODE_ROLE=booth
NODE_INDEX=1
DATA_DIR=./data
JWT_SECRET=festpass-stage1-secret-token-key-2026
LOG_LEVEL=info
ED25519_PRIVATE_KEY="${singleLinePrivate}"
ED25519_PUBLIC_KEY="${singleLinePublic}"
PEERS="B1=http://localhost:4001,B2=http://localhost:4002,B3=http://localhost:4003,G1=http://localhost:4004,G2=http://localhost:4005,G3=http://localhost:4006"
`;
    fs.writeFileSync(envPath, envContent, 'utf8');
    console.log(`Created default .env at ${envPath}`);
  }
}

runKeygen();
